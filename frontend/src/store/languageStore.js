const useLanguageStore = create(
  persist(
    (set, get) => ({
      language: 'en',

      setLanguage: (lang) => {
        set({ language: lang });
      },

      t: (key) => {
        const { language } = get();
        return translations[language]?.[key] || translations.en[key] || key;
      },

      getTranslations: () => {
        const { language } = get();
        return translations[language] || translations.en;
      },
    }),
    {
      name: 'language-storage',
    }
  )
);

export default useLanguageStore;
